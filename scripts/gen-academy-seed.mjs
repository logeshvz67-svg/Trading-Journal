// Generates supabase/seed_academy.sql from scripts/academy-content.mjs.
import { writeFileSync } from 'node:fs';
import { LESSONS, FLASHCARDS, DRILLS } from './academy-content.mjs';

const lit = (s) => `$mq$${s}$mq$`;
const json = (o) => `${lit(JSON.stringify(o))}::jsonb`;

let sql = `-- GENERATED by scripts/gen-academy-seed.mjs. Edit academy-content.mjs and run: npm run seed:academy
-- Re-runnable: rows are upserted by id, so your progress is kept.

`;
sql += `insert into public.lessons (id, zone, sort_order, title, content, quiz, pass_mark, est_minutes, is_stub) values\n`;
sql += LESSONS.map((l) => `(${lit(l.id)}, ${l.zone}, ${l.order}, ${lit(l.title)}, ${lit(l.content)}, ${json(l.quiz)}, 80, 10, ${l.is_stub ? 'true' : 'false'})`).join(',\n');
sql += `\non conflict (id) do update set zone = excluded.zone, sort_order = excluded.sort_order, title = excluded.title,
  content = excluded.content, quiz = excluded.quiz, pass_mark = excluded.pass_mark, est_minutes = excluded.est_minutes, is_stub = excluded.is_stub;\n\n`;

sql += `insert into public.flashcards (id, user_id, zone, front, back) values\n`;
sql += FLASHCARDS.map(([front, back, zone], i) => `(md5('mq-card-${i + 1}')::uuid, null, ${zone}, ${lit(front)}, ${lit(back)})`).join(',\n');
sql += `\non conflict (id) do update set zone = excluded.zone, front = excluded.front, back = excluded.back;\n\n`;

sql += `insert into public.drills (id, zone, title, kind, payload) values\n`;
sql += DRILLS.map((d) => `(${lit(d.id)}, ${d.zone}, ${lit(d.title)}, ${lit(d.kind)}, ${json(d.payload)})`).join(',\n');
sql += `\non conflict (id) do update set zone = excluded.zone, title = excluded.title, kind = excluded.kind, payload = excluded.payload;\n`;

writeFileSync(new URL('../supabase/seed_academy.sql', import.meta.url), sql);
console.log(`Wrote ${LESSONS.length} lessons, ${FLASHCARDS.length} flashcards, ${DRILLS.length} drills.`);
