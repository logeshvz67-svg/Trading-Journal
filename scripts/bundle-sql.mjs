// Concatenates every migration + seed into supabase/ALL_IN_ONE.sql for a single paste
// into the Supabase SQL editor on a FRESH project.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
const dir = new URL('../supabase/', import.meta.url);
const migrations = readdirSync(new URL('migrations/', dir)).filter((f) => f.endsWith('.sql')).sort();
const parts = [...migrations.map((f) => `migrations/${f}`), 'seed.sql', 'seed_academy.sql'];
const sql = parts.map((f) => `-- ============================== ${f}\n${readFileSync(new URL(f, dir), 'utf8')}`).join('\n\n');
writeFileSync(new URL('ALL_IN_ONE.sql', dir), `-- GENERATED by scripts/bundle-sql.mjs (npm run sql:bundle). For a FRESH Supabase project.\n\n${sql}`);
console.log(`Bundled ${parts.length} files into supabase/ALL_IN_ONE.sql`);
